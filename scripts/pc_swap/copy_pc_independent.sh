#!/usr/bin/env bash
#
# Carry the PC-independent supplementary material from the published 55-PC
# folder into the 2005-PC folder.
#
# A panel qualifies as PC-independent only if none of its inputs is a TOPMed
# residualized z-score or anything derived from one:
#
#   S2  RNA-seq QC          connectivity, |Z|>5 subject filter, PCA scree,
#                           PERMANOVA. Describes the cohort and the PCA itself.
#   S3  UMAP before/after   coordinates of the PCA objects; not underlier calls.
#   S7  cell-type vs PCs    correlation of PC1..80 with NNLS proportions. A
#                           property of the PC basis, swept over all PCs, so it
#                           does not move when the cut point moves.
#
# Their tables are copied too, which also makes make_supplementary_s2_s5.R take
# its documented S2/S3 skip path instead of recomputing WGCNA + UMAP.
#
# Everything else in the supplement (S1 sweeps, S4, S5, S6, S8, S9) is
# regenerated by the pipeline; S1/S9 happen to be PC-independent as well but
# are cheap enough to redraw from their own sources.
set -euo pipefail

ROOT="/net/topmed11/working/porchard/for-others/julie-and-esther/2025-11-17/sheyang/pre_Watershed_scripts"
SRC="$ROOT/final_paper_draft_pc55/supp_figs"
DST="/net/topmed11/working/porchard/for-others/julie-and-esther/2025-11-17/sheyang/submission_package_nov_2026/supp_figs"
mkdir -p "$DST/tables"

copied=0
copy_glob() {
  local pat="$1" f
  shopt -s nullglob
  for f in $pat; do
    cp -p "$f" "$DST/$(basename "$f")"
    copied=$((copied + 1))
  done
  shopt -u nullglob
}
copy_tbl() {
  local pat="$1" f
  shopt -s nullglob
  for f in $pat; do
    cp -p "$f" "$DST/tables/$(basename "$f")"
    copied=$((copied + 1))
  done
  shopt -u nullglob
}

echo "carrying PC-independent supplementary panels 55 PCs -> 2005 PCs"

# S2 / S3: RNA-seq QC and UMAP.
copy_glob "$SRC/FigS2*.png"; copy_glob "$SRC/FigS2*.pdf"
copy_glob "$SRC/FigS3*.png"; copy_glob "$SRC/FigS3*.pdf"
copy_glob "$SRC/Supplementary_Figure2.*"
copy_glob "$SRC/Supplementary_Figure3.*"
copy_tbl  "$SRC/tables/S2_*.tsv"
copy_tbl  "$SRC/tables/S3_*.tsv"

# S7: cell-type composition vs expression PCs (+ the signature tables that the
# S1 overlay and S8 reuse instead of recomputing NNLS).
copy_glob "$SRC/FigS7*.png"; copy_glob "$SRC/FigS7*.pdf"
copy_glob "$SRC/Supplementary_Figure7.*"
copy_glob "$SRC/FigS_celltype_pc_eval.*"
copy_tbl  "$SRC/tables/S7_*.tsv"

# gnomAD incidence comparison: external allele frequencies, no z-scores.
copy_tbl  "$SRC/tables/cohort_vs_gnomad_incidence_per_gene.tsv"

# Archived pre-overlay renderings of S1. No script regenerates these; they are
# one-off backups taken before the cell-type overlay was added to S1a/S1b, and
# S1a/S1b themselves come out byte-identical at 55 and 2005 PCs because the
# enrichment sweep spans the whole PC grid.
copy_glob "$SRC/FigS1a_sv_enrichment_no_overlay.*"
copy_glob "$SRC/FigS1b_ptv_enrichment_no_overlay.*"
copy_glob "$SRC/Supplementary_Figure1_no_overlay.*"

echo "copied $copied PC-independent files into $DST"
